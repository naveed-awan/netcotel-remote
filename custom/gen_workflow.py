#!/usr/bin/env python3
"""Generate .github/workflows/custom-build.yml from upstream flutter-build.yml.

Takes the Windows and macOS desktop jobs as they are upstream (toolchains, vcpkg,
build flags), applies custom/brand.py right after checkout, and swaps upstream's
signing/MSI/publish steps for unsigned, branded packaging. Re-run after merging
upstream; it stops with an error if a step it relies on was renamed or removed.

    python3 custom/gen_workflow.py
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SRC = ROOT / ".github/workflows/flutter-build.yml"
DST = ROOT / ".github/workflows/custom-build.yml"
BRAND = json.loads((HERE / "brand.json").read_text())
APP, DISPLAY, PREFIX = BRAND["app_name"], BRAND["display_name"], BRAND["file_prefix"]

VARIANT = "${{ inputs.variant }}"
VERSION = "${{ env.VERSION }}"
ARCH = "${{ matrix.job.arch }}"

HEADER = f"""\
# GENERATED by custom/gen_workflow.py from flutter-build.yml - do not edit by hand.
name: Build {DISPLAY}
run-name: {DISPLAY} ({VARIANT})

on:
  workflow_dispatch:
    inputs:
      variant:
        description: "kunde = incoming connections only, admin = full client"
        type: choice
        options: [kunde, admin]
        default: kunde

permissions:
  contents: write

"""

BRAND_STEP = f"""\
      - name: Apply branding
        shell: bash
        run: python3 custom/brand.py --variant {VARIANT}

"""

# Without an Apple certificate the app is signed ad hoc. build.py copies the service
# binary into the finished bundle, which breaks the seal Xcode made, so sign again.
MAC_DMG_STEP = f"""\
      - name: Sign ad hoc and create dmg
        run: |
          APP="./flutter/build/macos/Build/Products/Release/{APP}.app"
          codesign --force --deep --sign - --entitlements ./flutter/macos/Runner/Release.entitlements "$APP"
          codesign --verify --deep --strict --verbose=2 "$APP"
          CREATE_DMG="$(command -v create-dmg)"
          CREATE_DMG="$(readlink -f "$CREATE_DMG")"
          sed -i -e 's/MAXIMUM_UNMOUNTING_ATTEMPTS=3/MAXIMUM_UNMOUNTING_ATTEMPTS=7/' "$CREATE_DMG"
          create-dmg --volname "{DISPLAY}" --icon "{APP}.app" 200 190 --hide-extension "{APP}.app" --window-size 800 400 --app-drop-link 600 185 {PREFIX}-{VARIANT}-{VERSION}-{ARCH}.dmg "$APP"

"""


class Job:
    def __init__(self, name, block):
        self.name = name
        marker = "    steps:\n"
        if marker not in block:
            raise SystemExit(f"{name}: no steps section")
        cut = block.index(marker) + len(marker)
        self.head = block[:cut]
        self.steps = [s for s in re.split(r"(?m)^(?=      - )", block[cut:]) if s]

    def _index(self, step):
        hits = [i for i, s in enumerate(self.steps) if s.startswith(f"      - name: {step}\n")]
        if len(hits) != 1:
            raise SystemExit(f"{self.name}: expected one step named {step!r}, found {len(hits)}")
        return hits[0]

    def drop(self, *steps):
        for step in steps:
            del self.steps[self._index(step)]

    def insert_after(self, step, text):
        self.steps.insert(self._index(step) + 1, text)

    def swap(self, step, text):
        self.steps[self._index(step)] = text

    def replace(self, step, old, new):
        i = self._index(step)
        if self.steps[i].count(old) != 1:
            raise SystemExit(f"{self.name} / {step}: expected one {old!r}")
        self.steps[i] = self.steps[i].replace(old, new)

    def text(self):
        return self.head + "".join(self.steps)


def main():
    lines = SRC.read_text().splitlines(keepends=True)
    env_start = next(i for i, l in enumerate(lines) if l.rstrip() == "env:")
    jobs_start = next(i for i, l in enumerate(lines) if l.rstrip() == "jobs:")
    job_re = re.compile(r"^  ([A-Za-z0-9_-]+):\s*$")
    starts = [(i, m.group(1)) for i, l in enumerate(lines) if i > jobs_start and (m := job_re.match(l))]
    blocks = {}
    for n, (i, name) in enumerate(starts):
        end = starts[n + 1][0] if n + 1 < len(starts) else len(lines)
        blocks[name] = "".join(lines[i:end])

    def block(name):
        if name not in blocks:
            raise SystemExit(f"job not found upstream (renamed?): {name}")
        return blocks[name]

    win = Job("build-for-windows-flutter", block("build-for-windows-flutter"))
    win.insert_after("Checkout source code", BRAND_STEP)
    # The MSI would install under the stock name, so only the self-extracting exe is shipped.
    win.drop("Upload unsigned", "Sign rustdesk files", "Add MSBuild to PATH", "Build msi",
             "Build pre-built MSI template", "Upload unsigned msi template",
             "Sign rustdesk self-extracted file")
    win.replace("Build self-extracted executable",
                f"./SignOutput/rustdesk-{VERSION}-{ARCH}.exe",
                f"./SignOutput/{PREFIX}-{VARIANT}-{VERSION}-{ARCH}.exe")
    win.replace("Publish Release", "            ./SignOutput/rustdesk-*.msi\n", "")
    win.replace("Publish Release", "./SignOutput/rustdesk-*.exe", f"./SignOutput/{PREFIX}-*.exe")

    mac = Job("build-for-macOS", block("build-for-macOS"))
    mac.insert_after("Checkout source code", BRAND_STEP)
    mac.drop("Upload unsigned macOS app", "Codesign app and create signed dmg", "Rename rustdesk")
    mac.swap("create unsigned dmg", MAC_DMG_STEP)
    mac.replace("Publish DMG package", f"rustdesk*-{ARCH}.dmg", f"{PREFIX}-*-{ARCH}.dmg")

    out = ("".join(lines[env_start:jobs_start]) + "jobs:\n"
           + block("generate-bridge") + block("build-RustDeskTempTopMostWindow")
           + win.text() + mac.text())
    out = out.replace("inputs.upload-artifact", "true")
    out = out.replace("inputs.upload-tag", "format('build-{0}', inputs.variant)")
    leftover = set(re.findall(r"inputs\.[\w-]+", out)) - {"inputs.variant"}
    if leftover:
        raise SystemExit(f"unhandled workflow inputs: {sorted(leftover)}")
    DST.write_text(HEADER + out)
    print(f"wrote {DST.relative_to(ROOT)} ({out.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
