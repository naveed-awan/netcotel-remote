#!/usr/bin/env python3
"""Generate .github/workflows/custom-build.yml from upstream flutter-build.yml.

Keeps only the Windows and macOS desktop jobs, so the custom client can be
built without the Android/Linux/iOS jobs. Re-run after merging upstream:

    python3 custom/gen_workflow.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / ".github/workflows/flutter-build.yml"
DST = ROOT / ".github/workflows/custom-build.yml"

KEEP_JOBS = [
    "generate-bridge",
    "build-RustDeskTempTopMostWindow",
    "build-for-windows-flutter",
    "build-for-macOS",
]
RELEASE_TAG = "custom-build"

HEADER = """\
# GENERATED by custom/gen_workflow.py from flutter-build.yml - do not edit by hand.
name: Custom client build (Windows + macOS)

on:
  workflow_dispatch:

permissions:
  contents: write

"""

lines = SRC.read_text().splitlines(keepends=True)
env_start = next(i for i, l in enumerate(lines) if l.rstrip() == "env:")
jobs_start = next(i for i, l in enumerate(lines) if l.rstrip() == "jobs:")

job_re = re.compile(r"^  ([A-Za-z0-9_-]+):\s*$")
starts = [(i, m.group(1)) for i, l in enumerate(lines) if i > jobs_start and (m := job_re.match(l))]
blocks = {}
for n, (i, name) in enumerate(starts):
    end = starts[n + 1][0] if n + 1 < len(starts) else len(lines)
    blocks[name] = "".join(lines[i:end])

missing = [j for j in KEEP_JOBS if j not in blocks]
if missing:
    raise SystemExit(f"jobs not found upstream (renamed?): {missing}")

out = HEADER + "".join(lines[env_start:jobs_start]) + "jobs:\n" + "".join(blocks[j] for j in KEEP_JOBS)
out = out.replace("inputs.upload-artifact", "true").replace("inputs.upload-tag", f"'{RELEASE_TAG}'")
if "inputs." in out:
    raise SystemExit("unhandled workflow input left in output")
DST.write_text(out)
print(f"wrote {DST.relative_to(ROOT)} ({out.count(chr(10))} lines)")
